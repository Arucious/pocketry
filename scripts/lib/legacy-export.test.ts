import { execFile } from "node:child_process";
import { createHash } from "node:crypto";
import { mkdtemp, readFile, readdir, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { promisify } from "node:util";
import { strFromU8, unzipSync } from "fflate";
import { afterEach, describe, expect, it } from "vitest";

import upstream from "../fixtures/upstream-empty-bins.json";
import { EXPORT_QUALITY } from "../../client/src/lib/gridfinity/bin";
import { readProjectFile } from "./export-bin";

const run = promisify(execFile);
const repository = fileURLToPath(new URL("../../", import.meta.url));
const directories: string[] = [];
async function temporaryDirectory(): Promise<string> {
  const directory = await mkdtemp(join(tmpdir(), "pocketry-legacy-cli-"));
  directories.push(directory);
  return directory;
}
afterEach(async () => {
  await Promise.all(directories.splice(0).map(path => rm(path, { recursive: true, force: true })));
});

const sha256 = (bytes: Uint8Array | string) => createHash("sha256").update(bytes).digest("hex");

/** These references were generated by the pinned upstream source, not this exporter. */
describe("original empty-bin CLI compatibility", () => {
  it("uses the same pinned kernel and export resolution as the upstream references", async () => {
    const metadata = JSON.parse(await readFile(join(repository, "node_modules/manifold-3d/package.json"), "utf8"));
    expect(metadata.version).toBe(upstream.manifoldVersion);
    expect(EXPORT_QUALITY).toEqual(upstream.quality);
  });

  it.each(upstream.fixtures)("preserves upstream STL and 3MF geometry: $case", async fixture => {
    const directory = await temporaryDirectory();
    const spec = fixture.input;
    // The default case deliberately supplies no dimensions or style options.
    const args = fixture.case === "default" ? [] : [
      `${spec.gridX}X${spec.gridY}X${spec.heightUnits}`, "--fill", spec.fill,
      ...(spec.lip === "none" ? ["--no-lip"] : []),
    ];
    await run(process.execPath, ["--import", "tsx", "scripts/export-bin.ts", ...args, "--out", directory], {
      cwd: repository, timeout: 25_000, maxBuffer: 1024 * 1024,
    });
    expect((await readdir(directory)).sort()).toEqual([
      `${fixture.filename}.3mf`, `${fixture.filename}.pocketry.json`, `${fixture.filename}.stl`,
    ]);
    const stl = await readFile(join(directory, `${fixture.filename}.stl`));
    expect(stl.readUInt32LE(80)).toBe(fixture.triangles);
    // Ignore the descriptive 80-byte header; normals and every triangle byte must match.
    expect(sha256(stl.subarray(80))).toBe(fixture.stlPayloadSha256);
    const model = strFromU8(unzipSync(await readFile(join(directory, `${fixture.filename}.3mf`)))["3D/3dmodel.model"]);
    expect(model).toContain('unit="millimeter"');
    const meshes = model.match(/<mesh>[\s\S]*?<\/mesh>/g);
    expect(meshes).toHaveLength(1);
    expect(sha256(meshes![0])).toBe(fixture.threeMfMeshSha256);
    const project = await readProjectFile(join(directory, `${fixture.filename}.pocketry.json`));
    expect(project.spec).toMatchObject(spec);
    expect(project.cutouts).toEqual([]);
    expect(project.fingerHoles).toEqual([]);
  }, 30_000);

  it.each([
    ["0x1x6"], ["2x3x6", "--fill", "invalid"], ["--out"], ["--unknown"],
  ])("rejects invalid legacy requests without artifacts: %j", async (...args) => {
    const directory = await temporaryDirectory();
    await expect(run(process.execPath, ["--import", "tsx", "scripts/export-bin.ts", "--out", directory, ...args], {
      cwd: repository, timeout: 25_000,
    })).rejects.toMatchObject({ code: 1 });
    expect(await readdir(directory)).toEqual([]);
  }, 30_000);

  it("keeps legacy repeated dimensions and flags with the last output directory", async () => {
    const directory = await temporaryDirectory();
    const superseded = await temporaryDirectory();
    const reference = upstream.fixtures.find(fixture => fixture.case === "solid-no-lip")!;
    await run(process.execPath, ["--import", "tsx", "scripts/export-bin.ts",
      "1x1x2", "4x2x3", "--fill", "none", "--fill", "solid", "--no-lip", "--no-lip",
      "--out", superseded, "--out", directory], { cwd: repository, timeout: 25_000 });
    expect(await readdir(superseded)).toEqual([]);
    const stl = await readFile(join(directory, `${reference.filename}.stl`));
    expect(sha256(stl.subarray(80))).toBe(reference.stlPayloadSha256);
  }, 30_000);
});
